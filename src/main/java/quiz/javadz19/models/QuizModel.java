    /**
     * Возвращает список всех доступных категорий.
     */
    public static List<String> getCategories() {
        return CATEGORIES;
    }

    /**
     * Возвращает список вопросов для заданной категории.
     * Если категория не найдена, возвращает пустой список.
     */
    public static List<Question> getQuestionsByCategory(String category) {
        return ALL_QUESTIONS.stream()
                .filter(q -> q.getCategory().equalsIgnoreCase(category))
                .collect(Collectors.toList());
    }

    /**
     * Проверяет ответ пользователя для заданного вопроса.
     * @param question текущий вопрос
     * @param answerParam ответ пользователя (буква для вариантов, строка для текстового ввода)
     * @param isTimeout true, если время истекло (ответ не засчитывается)
     * @return true – ответ правильный, false – неправильный или таймаут
     */
    public static boolean checkAnswer(Question question, String answerParam, boolean isTimeout) {
        // При таймауте ответ автоматически неверный
        if (isTimeout) {
            return false;
        }

        if (question.isTextInput()) {
            // Текстовый вопрос: сравнение без учёта регистра и лишних пробелов
            if (answerParam != null) {
                String userAnswer = answerParam.trim();
                String correctAns = question.getCorrectText().trim();
                return userAnswer.equalsIgnoreCase(correctAns);
            }
            return false;
        } else {
            // Вопрос с вариантами: ответ должен быть одной буквой, совпадающей с correct
            if (answerParam != null && answerParam.length() == 1) {
                char userAnswer = answerParam.charAt(0);
                return userAnswer == question.getCorrect();
            }
            return false;
        }
    }
